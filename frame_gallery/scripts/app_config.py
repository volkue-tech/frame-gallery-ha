def _choices(field: FilterField) -> list[str]:
    if field is FilterField.COLOR:
        # Native Supervisor list controls display their values verbatim.
        # Use readable labels; the existing vocabulary normalizes them to keys.
        return ["any", *(entry.label for entry in BUILTIN_VOCABULARY.entries_for(field))]
    return ["any", *(entry.key for entry in BUILTIN_VOCABULARY.entries_for(field))]


def options() -> dict[str, Value]:
    """The defaults the Supervisor offers (§15.1). ``tv_host`` has none: the
    app cannot start until the user enters it (B1)."""
    return {
        "source": DEFAULT_SOURCE.value,
        "color": "any",
        "landscape_only": True,
        "strict_tv_format": True,
        "fit_mode": "contain",
    }


def schema() -> dict[str, Value]:
    return {
        "tv_host": TV_HOST_SCHEMA,
        "source": f"list({'|'.join(SOURCES)})",
        "color": f"list({'|'.join(_choices(FilterField.COLOR))})?",
        "landscape_only": "bool",
        "strict_tv_format": "bool",
        "fit_mode": "list(contain|cover)",
        "artist": "str(0,255)?",
        "department": f"list({'|'.join(_choices(FilterField.DEPARTMENT))})?",
        "style": f"list({'|'.join(_choices(FilterField.STYLE))})?",
        "background_color": BACKGROUND_SCHEMA + "?",
        "source_helper": HELPER_SCHEMA,
        "department_helper": HELPER_SCHEMA,
        "style_helper": HELPER_SCHEMA,
        "color_helper": HELPER_SCHEMA,
        "artist_helper": HELPER_SCHEMA,
        "log_level": "list(info|debug)?",
        "loading_timer": r"match(^timer\.[a-z0-9_]{1,64}$)?",
        "artwork_info_helper": r"match(^input_text\.[a-z0-9_]{1,64}$)?",
        "background_mode": "bool?",
        "current_state_refresh": "bool?",
        "resume_state_entity": r"match(^(?:media_player|remote)\.[a-z0-9_]{1,64}$)?",
    }


def config() -> dict[str, Value]:
    """``config.yaml`` (§17.1, D-129). Supervisor pulls the independently
    verified per-architecture release images; its tag is ``version``.
    Experimental is the supported Supervisor lifecycle flag for this beta."""
    return {
        "name": "Frame Gallery \u2013 Samsung Frame TV",
        "version": __version__,
        "slug": "frame_gallery",
        "description": "Samsung Frame TV artwork from museums or your own images.",
        "arch": ["aarch64", "amd64"],
        "image": "ghcr.io/volkue-tech/frame-gallery-ha-{arch}",
        "url": "https://github.com/volkue-tech/frame-gallery-ha",
        "startup": "application",
        "boot": "manual",
        "stdin": True,
        "init": False,
        "stage": "experimental",
        "homeassistant": "2026.2.0",
        "homeassistant_api": True,
        "tmpfs": True,
        "timeout": 20,
        "map": [{"type": "media", "read_only": False}],
        "backup_exclude": ["cache/**", "state/quarantine/**", "tv/**"],
        "options": options(),
        "schema": schema(),
    }


